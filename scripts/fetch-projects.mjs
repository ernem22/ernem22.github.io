/* ──────────────────────────────────────────────────────────────
   Build-time GitHub snapshot for the Projects panel.

   Reads site.github from data.js, asks GitHub for the user's repos and
   keeps the ones tagged with that topic. The result is written to
   projects.js as `window.GITHUB_REPOS`, which index.html loads just
   after data.js. main.js turns those repos into project cards.

   Design goals:
   - Best effort: a network failure never breaks `npm run build`.
   - No secrets in the repo: GITHUB_TOKEN (optional) is read from env
     only; it lifts the 60 req/h anonymous limit.
   - No churn: the file is only rewritten when the repo list changes.
   - Filesystem-friendly: data.js stays the offline fallback, so the
     site still renders when projects.js is missing or empty.

   Run:
     npm run projects   # always fetch and rewrite projects.js
     npm run build      # refresh it only when the snapshot is stale
   ────────────────────────────────────────────────────────────── */
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import vm from "node:vm";

const root = new URL("../", import.meta.url);
const outFile = new URL("projects.js", root);
const TTL = 6 * 60 * 60 * 1000;

function readConfig() {
  const ctx = vm.createContext({ window: {} });
  vm.runInContext(readFileSync(new URL("data.js", root), "utf8"), ctx, {
    filename: "data.js",
  });
  const gh = ctx.window.DATA?.site?.github || {};
  return {
    user: gh.user || "ernem22",
    topic: gh.topic || "portfolio",
    limit: Number(gh.limit) || 100,
    includeForks: !!gh.includeForks,
  };
}

function snapshot(repo, fallbackOwner) {
  return {
    name: repo.name,
    description: repo.description || "",
    url: repo.html_url,
    homepage: repo.homepage || "",
    language: repo.language || "",
    topics: Array.isArray(repo.topics) ? repo.topics : [],
    stars: repo.stargazers_count || 0,
    forks: repo.forks_count || 0,
    pushed: repo.pushed_at || "",
    created: repo.created_at || "",
    owner: repo.owner?.login || fallbackOwner,
    avatar: repo.owner?.avatar_url || "",
    archived: !!repo.archived,
  };
}

async function getJson(url, token) {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "portfolio-build",
    "X-GitHub-Api-Version": "2022-11-28",
  };
  if (token) headers.Authorization = `Bearer ${token}`;
  const res = await fetch(url, {
    headers,
    signal: AbortSignal.timeout(8000),
  });
  if (!res.ok) {
    const remaining = res.headers.get("x-ratelimit-remaining");
    throw new Error(
      `GitHub ${res.status} ${res.statusText} for ${url}` +
        (remaining != null ? ` (rate limit remaining: ${remaining})` : ""),
    );
  }
  return res.json();
}

async function listRepos({ user, limit }, token) {
  const repos = [];
  for (let page = 1; repos.length < limit && page <= 10; page++) {
    const url =
      `https://api.github.com/users/${encodeURIComponent(user)}/repos` +
      `?per_page=100&page=${page}&sort=pushed&type=owner`;
    const batch = await getJson(url, token);
    if (!Array.isArray(batch) || batch.length === 0) break;
    repos.push(...batch);
    if (batch.length < 100) break;
  }
  return repos.slice(0, limit);
}

function render(list) {
  return (
    "/* Generated by scripts/fetch-projects.mjs — do not edit by hand.\n" +
    "   Source: GitHub repos tagged with the topic in data.js (site.github).\n" +
    "   Regenerate with `npm run projects`, then `npm run build`. */\n" +
    `window.GITHUB_REPOS = ${JSON.stringify(list, null, 2)};\n`
  );
}

export async function fetchProjects({ force = false, quiet = false } = {}) {
  if (process.env.PROJECTS_OFFLINE === "1")
    return { skipped: "PROJECTS_OFFLINE=1" };

  const config = readConfig();
  if (!force && existsSync(outFile)) {
    const prev = readFileSync(outFile, "utf8");
    const age = Date.now() - statSync(outFile).mtimeMs;
    // An empty snapshot retries sooner, but never on every commit.
    const hasRepos = /window\.GITHUB_REPOS\s*=\s*\[\s*\{/.test(prev);
    if (age < (hasRepos ? TTL : 30 * 60 * 1000))
      return { skipped: `fresh (${Math.round(age / 60000)} min)` };
  }

  try {
    const repos = await listRepos(config, process.env.GITHUB_TOKEN);
    const tagged = repos.filter(
      (repo) =>
        Array.isArray(repo.topics) &&
        repo.topics.includes(config.topic) &&
        (config.includeForks || !repo.fork) &&
        !repo.archived,
    );

    if (!tagged.length) {
      const prev = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
      const empty = !/window\.GITHUB_REPOS\s*=\s*\[\s*\{/.test(prev);
      if (empty) writeFileSync(outFile, render([]));
      if (!quiet)
        console.warn(
          `fetch-projects: no public repos tagged "${config.topic}" for @${config.user}. ` +
            `Add the topic on GitHub (About → Topics) and run \`npm run projects\`.` +
            " Keeping the data.js projects as fallback.",
        );
      return { count: 0, note: "no tagged repos; fallback kept" };
    }

    const list = tagged.map((repo) => snapshot(repo, config.user));
    const next = render(list);
    const prev = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
    if (next !== prev) writeFileSync(outFile, next);
    if (!quiet)
      console.log(
        `projects.js  ${tagged.length} repo(s) tagged "${config.topic}"` +
          (next === prev ? " (up to date)" : ""),
      );
    return { count: tagged.length };
  } catch (error) {
    if (!quiet)
      console.warn(
        `fetch-projects: ${error.message}. Keeping the existing projects.js; ` +
          "the site will fall back to data.js.",
      );
    return { error: error.message };
  }
}

const runDirectly =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (runDirectly) {
  // Manual runs always refresh; only the build uses the cached snapshot.
  const result = await fetchProjects({ force: true });
  if (result.error) process.exitCode = 0; // best effort: never fail a build
}
